-- =====================================================================
-- SCHEMA — SISTEMA DE BARBERÍA (PostgreSQL / Supabase)
-- Equivalente 1:1 de database/schema.sql (SQL Server).
--
-- Cómo usarlo en Supabase:
--   1. Dashboard → SQL Editor → pegar y ejecutar este archivo.
--   2. Ejecutar database/postgres/datos_prueba.sql (opcional).
--   3. En .env usar la cadena JDBC de Supabase (ver .env.example).
--
-- Decisiones de portabilidad (no cambian el código Java):
--   - Las banderas (activo, activa, ...) son SMALLINT 0/1 en vez de BOOLEAN,
--     porque los DAO comparan con "= 1" / "= 0", igual que BIT en SQL Server.
--   - IDENTITY → GENERATED BY DEFAULT AS IDENTITY.
--   - NVARCHAR → VARCHAR (UTF-8 nativo), NVARCHAR(MAX) → TEXT.
--   - DATETIME2 / SYSDATETIME() → TIMESTAMP / now().
--
-- Seguridad Supabase: se activa RLS en todas las tablas SIN políticas.
-- Así la API pública (PostgREST con anon key) no expone datos; el backend
-- Java se conecta con el rol "postgres" (dueño), que no está sujeto a RLS.
-- =====================================================================

DROP TABLE IF EXISTS recuperaciones_password, calificaciones, cita_servicios, citas, carritos_items,
    cliente_suscripciones, suscripciones, productos, servicios, superadmins,
    empleados, clientes, barberias, personas CASCADE;

-- ─── personas ────────────────────────────────────────────────────────
CREATE TABLE personas (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_identidad VARCHAR(20)  NOT NULL UNIQUE,
    tipo_documento      VARCHAR(20)  NOT NULL DEFAULT 'RUT'
                        CONSTRAINT ck_personas_tipo_doc CHECK (tipo_documento IN ('RUT','CPF','DNI','PASAPORTE','OTRO')),
    nombre              VARCHAR(100) NOT NULL,
    apellido            VARCHAR(100) NOT NULL,
    email               VARCHAR(150) NOT NULL UNIQUE,
    telefono            VARCHAR(20)  NULL,
    password_hash       VARCHAR(255) NOT NULL,
    foto_url            VARCHAR(500) NULL,
    idioma_preferido    VARCHAR(5)   NOT NULL DEFAULT 'es',
    pais_codigo         CHAR(2)      NOT NULL DEFAULT 'CL',
    auth_provider       VARCHAR(20)  NOT NULL DEFAULT 'LOCAL'
                        CONSTRAINT ck_personas_auth CHECK (auth_provider IN ('LOCAL','GOOGLE','GITHUB')),
    mfa_habilitado      SMALLINT     NOT NULL DEFAULT 0 CHECK (mfa_habilitado IN (0,1)),
    fecha_registro      TIMESTAMP    NOT NULL DEFAULT now(),
    activo              SMALLINT     NOT NULL DEFAULT 1 CHECK (activo IN (0,1)),
    -- Control de intentos de login: 5 fallos → 15 s, 10 → 30 s, 15 → cuenta bloqueada
    intentos_fallidos   INT          NOT NULL DEFAULT 0,
    bloqueado_hasta     TIMESTAMP    NULL,
    bloqueada           SMALLINT     NOT NULL DEFAULT 0 CHECK (bloqueada IN (0,1))
);

-- ─── barberias ───────────────────────────────────────────────────────
CREATE TABLE barberias (
    id                        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                    VARCHAR(200) NOT NULL,
    direccion                 VARCHAR(300) NULL,
    telefono                  VARCHAR(20)  NULL,
    email                     VARCHAR(150) NULL,
    logo_url                  VARCHAR(500) NULL,
    descripcion               TEXT         NULL,
    activa                    SMALLINT     NOT NULL DEFAULT 1 CHECK (activa IN (0,1)),
    pais_codigo               CHAR(2)      NOT NULL DEFAULT 'CL',
    moneda_codigo             CHAR(3)      NOT NULL DEFAULT 'CLP',
    zona_horaria              VARCHAR(50)  NOT NULL DEFAULT 'America/Santiago',
    suscripciones_habilitadas SMALLINT     NOT NULL DEFAULT 0 CHECK (suscripciones_habilitadas IN (0,1)),
    fecha_creacion            TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_barberias_activa ON barberias(activa);
CREATE INDEX idx_barberias_pais   ON barberias(pais_codigo);

-- ─── clientes / empleados / superadmins ──────────────────────────────
CREATE TABLE clientes (
    id               INT PRIMARY KEY REFERENCES personas(id) ON DELETE CASCADE ON UPDATE CASCADE,
    puntos_fidelidad INT NOT NULL DEFAULT 0
);

CREATE TABLE empleados (
    id          INT PRIMARY KEY REFERENCES personas(id) ON DELETE CASCADE ON UPDATE CASCADE,
    barberia_id INT         NOT NULL REFERENCES barberias(id) ON DELETE CASCADE ON UPDATE CASCADE,
    rol         VARCHAR(20) NOT NULL DEFAULT 'BARBERO'
                CONSTRAINT ck_empleados_rol CHECK (rol IN ('BARBERO','ADMIN_BARBERIA')),
    activo      SMALLINT    NOT NULL DEFAULT 1 CHECK (activo IN (0,1))
);
CREATE INDEX idx_empleados_barberia ON empleados(barberia_id);
CREATE INDEX idx_empleados_rol      ON empleados(rol);

CREATE TABLE superadmins (
    id INT PRIMARY KEY REFERENCES personas(id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- ─── servicios ───────────────────────────────────────────────────────
CREATE TABLE servicios (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barberia_id      INT           NOT NULL REFERENCES barberias(id) ON DELETE CASCADE ON UPDATE CASCADE,
    nombre           VARCHAR(200)  NOT NULL,
    descripcion      TEXT          NULL,
    precio           NUMERIC(10,2) NOT NULL,
    duracion_minutos INT           NOT NULL DEFAULT 30,
    activo           SMALLINT      NOT NULL DEFAULT 1 CHECK (activo IN (0,1))
);
CREATE INDEX idx_servicios_barberia ON servicios(barberia_id);

-- ─── citas ───────────────────────────────────────────────────────────
CREATE TABLE citas (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barberia_id    INT           NOT NULL REFERENCES barberias(id),
    cliente_id     INT           NOT NULL REFERENCES clientes(id),
    empleado_id    INT           NOT NULL REFERENCES empleados(id),
    fecha          DATE          NOT NULL,
    hora           TIME(0)       NOT NULL,
    estado         VARCHAR(20)   NOT NULL DEFAULT 'PENDIENTE'
                   CONSTRAINT ck_citas_estado CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA','COMPLETADA')),
    precio_total   NUMERIC(10,2) NULL,
    notas          TEXT          NULL,
    fecha_creacion TIMESTAMP     NOT NULL DEFAULT now()
);
CREATE INDEX idx_citas_barberia_fecha ON citas(barberia_id, fecha);
CREATE INDEX idx_citas_empleado_fecha ON citas(empleado_id, fecha);
CREATE INDEX idx_citas_cliente        ON citas(cliente_id);
CREATE INDEX idx_citas_ganancias      ON citas(barberia_id, estado, fecha) INCLUDE (empleado_id, precio_total);
-- Anti doble reserva (índice parcial, equivalente al índice filtrado de SQL Server)
CREATE UNIQUE INDEX ux_citas_barbero_slot ON citas(empleado_id, fecha, hora) WHERE estado <> 'CANCELADA';

CREATE TABLE cita_servicios (
    cita_id     INT NOT NULL REFERENCES citas(id) ON DELETE CASCADE,
    servicio_id INT NOT NULL REFERENCES servicios(id),
    PRIMARY KEY (cita_id, servicio_id)
);

-- ─── productos / carrito ─────────────────────────────────────────────
CREATE TABLE productos (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barberia_id INT           NOT NULL REFERENCES barberias(id) ON DELETE CASCADE ON UPDATE CASCADE,
    nombre      VARCHAR(200)  NOT NULL,
    descripcion TEXT          NULL,
    precio      NUMERIC(10,2) NOT NULL,
    stock       INT           NOT NULL DEFAULT 0,
    categoria   VARCHAR(30)   NOT NULL DEFAULT 'OTRO'
                CONSTRAINT ck_productos_categoria CHECK (categoria IN (
                    'SHAMPOO','BALSAMO','CREMA_BARBEAR','CREMA_MODELADORA',
                    'ACEITE_BARBA','CERA_CABELLO','LOCION','OTRO')),
    imagen_url  VARCHAR(500)  NULL,
    activo      SMALLINT      NOT NULL DEFAULT 1 CHECK (activo IN (0,1))
);
CREATE INDEX idx_productos_barberia  ON productos(barberia_id);
CREATE INDEX idx_productos_categoria ON productos(categoria);

CREATE TABLE carritos_items (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id     INT       NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
    barberia_id    INT       NOT NULL REFERENCES barberias(id),
    producto_id    INT       NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
    cantidad       INT       NOT NULL DEFAULT 1,
    fecha_agregado TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT uk_carrito_item UNIQUE (cliente_id, barberia_id, producto_id)
);
CREATE INDEX idx_carrito_cliente_barberia ON carritos_items(cliente_id, barberia_id);

-- ─── suscripciones ───────────────────────────────────────────────────
CREATE TABLE suscripciones (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barberia_id     INT           NOT NULL REFERENCES barberias(id) ON DELETE CASCADE ON UPDATE CASCADE,
    nombre          VARCHAR(200)  NOT NULL,
    tipo            VARCHAR(20)   NOT NULL
                    CONSTRAINT ck_suscripciones_tipo CHECK (tipo IN ('POR_CITA','MENSUAL','AMBAS')),
    precio_por_cita NUMERIC(10,2) NULL,
    precio_mensual  NUMERIC(10,2) NULL,
    descripcion     TEXT          NULL,
    activa          SMALLINT      NOT NULL DEFAULT 1 CHECK (activa IN (0,1))
);
CREATE INDEX idx_suscripciones_barberia ON suscripciones(barberia_id);

CREATE TABLE cliente_suscripciones (
    id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id        INT      NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
    suscripcion_id    INT      NOT NULL REFERENCES suscripciones(id),
    fecha_inicio      DATE     NOT NULL,
    fecha_vencimiento DATE     NULL,
    activa            SMALLINT NOT NULL DEFAULT 1 CHECK (activa IN (0,1))
);
CREATE INDEX idx_cli_subs_cliente     ON cliente_suscripciones(cliente_id);
CREATE INDEX idx_cli_subs_suscripcion ON cliente_suscripciones(suscripcion_id);

-- ─── calificaciones ──────────────────────────────────────────────────
CREATE TABLE calificaciones (
    id                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id            INT       NOT NULL UNIQUE REFERENCES citas(id),
    cliente_id         INT       NOT NULL REFERENCES clientes(id),
    barberia_id        INT       NOT NULL REFERENCES barberias(id),
    empleado_id        INT       NOT NULL REFERENCES empleados(id),
    estrellas_barberia SMALLINT  NOT NULL CONSTRAINT ck_cal_barberia CHECK (estrellas_barberia BETWEEN 1 AND 5),
    estrellas_barbero  SMALLINT  NOT NULL CONSTRAINT ck_cal_barbero  CHECK (estrellas_barbero  BETWEEN 1 AND 5),
    comentario         TEXT      NULL,
    fecha              TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_calificaciones_barberia ON calificaciones(barberia_id);
CREATE INDEX idx_calificaciones_empleado ON calificaciones(empleado_id);

-- ─── recuperaciones_password ("¿Olvidaste tu contraseña?") ───────────
CREATE TABLE recuperaciones_password (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona_id     INT          NOT NULL REFERENCES personas(id) ON DELETE CASCADE,
    codigo_hash    VARCHAR(100) NOT NULL,
    expira         TIMESTAMP    NOT NULL,
    intentos       INT          NOT NULL DEFAULT 0,
    usado          SMALLINT     NOT NULL DEFAULT 0 CHECK (usado IN (0,1)),
    fecha_creacion TIMESTAMP    NOT NULL
);
CREATE INDEX idx_recuperaciones_persona ON recuperaciones_password(persona_id, usado);

-- ─── RLS: bloquear acceso directo vía API pública de Supabase ────────
DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['personas','barberias','clientes','empleados','superadmins',
        'servicios','citas','cita_servicios','productos','carritos_items',
        'suscripciones','cliente_suscripciones','calificaciones','recuperaciones_password']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    END LOOP;
END $$;
